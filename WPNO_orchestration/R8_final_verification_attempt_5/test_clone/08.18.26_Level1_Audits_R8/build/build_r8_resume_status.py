#!/usr/bin/env python3
"""What R8 has built, and where the evidence for each claim is.

Every path here is checked by `build/validate_status_record.py`, and where a
`<key>_sha256` sibling exists the digest is checked too. R7's own status
record named a superseded manifest that was never written; its digest and
entry count matched the file that does exist under a different name, so the
content was right and only the name was wrong. A dangling path gates nothing.
It misleads a reader into looking for evidence under a name it does not have.

One category of artefact is named without a digest, and the reason is worth
stating rather than leaving as an omission. `build/R8_TEST_SUITE_RESULTS.json`
is written by the test run, and the test suite validates this record. Binding
its digest here would mean the record could only be valid until the next time
the suite that validates it ran -- a self-reference that fails on its second
execution and says nothing about integrity when it fails. The path is bound;
the digest is left to the manifest, which is written after the suite has run
and is not regenerated by it.
"""

import json
import os
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from automation import hashing, path_policy  # noqa: E402

OUT = os.path.join(ROOT, "build", "R8_RESUME_STATUS.json")

# Named paths whose digest is deliberately not bound here. See the docstring.
#
# All four are rewritten by a run that also validates this record, so binding
# their digests makes the record valid only until the next such run. That is
# not a hypothetical: it failed three times during the R8 build, once for
# each file added to this set, and each time the failure said nothing about
# integrity -- only that the record had been written before the run that
# regenerates it rather than after. The path is bound; the digest is left to
# the build manifest, which is generated last and is not regenerated by any
# verification step.
SELF_REGENERATING = frozenset((
    "build/R8_TEST_SUITE_RESULTS.json",
    "build/R8_STATIC_SAFETY_REPORT.json",
    "build/R8_CHANGED_FILES.sha256",
    "work/_rehearsal_r8/REHEARSAL_REPORT.json",
))

SECTIONS = {
    "execution_engine_repair": {
        "shared_executor": "automation/in_process_executor.py",
        "operations": "automation/in_process_ops.py",
        "operation_catalogue": "automation/operation_catalog.py",
        "controller": "automation/controller.py",
    },
    "plans": {
        "coverage_manifest":
            "build/candidate_plans_r8/PLAN_COVERAGE_MANIFEST.json",
        "coverage_manifest_digest":
            "build/candidate_plans_r8/PLAN_COVERAGE_MANIFEST.sha256",
        "specifications": "build/candidate_plan_specs.py",
        "library": "build/plan_library.py",
    },
    "rehearsal": {
        "harness": "build/rehearse_candidate_plans.py",
        "report": "work/_rehearsal_r8/REHEARSAL_REPORT.json",
        "fixture_staging_record":
            "work/_rehearsal_r8/FIXTURE_STAGING_RECORD.json",
        "input_substitutions":
            "work/_rehearsal_r8/REHEARSAL_INPUT_SUBSTITUTIONS.json",
        "input_stager": "build/stage_r8_rehearsal_inputs.py",
    },
    "measurement_records": {
        "in_process_count_reconciliation":
            "build/IN_PROCESS_COUNT_RECONCILIATION.json",
        "control_expectation_coverage":
            "build/CONTROL_EXPECTATION_COVERAGE.json",
        "control_expectation_table": "build/control_expectations.py",
    },
    "migration": {
        "route": "automation/migration.py",
        "plan": "build/migration_plan_r7_to_r8/MIGRATION_PLAN.json",
        "plan_digest": "build/migration_plan_r7_to_r8/MIGRATION_PLAN.sha256",
        "builder": "build/build_migration_plan.py",
        "tests": "automation/package_tests/test_r8_migration.py",
    },
    "lineage": {
        "compact_lineage_record": "lineage/R8_LINEAGE.json",
        "compact_lineage_digest": "lineage/R8_LINEAGE.sha256",
        "predecessor_baseline": "lineage/R7_BASELINE_MANIFEST.json",
        "predecessor_incident":
            "lineage/R7_POST_FREEZE_INCIDENT/INCIDENT_MANIFEST.sha256",
    },
    "tests_and_safety": {
        "results": "build/R8_TEST_SUITE_RESULTS.json",
        "runner": "build/run_test_suites.py",
        "static_safety_report": "build/R8_STATIC_SAFETY_REPORT.json",
        "static_safety_review": "build/r8_static_safety_review.py",
    },
}


def main():
    record = {
        "schema": "wpno.level1.resume-status/1",
        "revision": "R8",
        "predecessor": "R7",
        "recorded_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "mode_at_record": open(os.path.join(ROOT, "MODE"),
                               encoding="utf-8").read().strip(),
        "digests_deliberately_unbound": sorted(SELF_REGENERATING),
        "why_some_digests_are_unbound": (
            "these files are written by the run that validates this record; "
            "binding their digests would make the record valid only until the "
            "next run of the suite that checks it"),
    }
    missing = []
    for section, entries in sorted(SECTIONS.items()):
        block = {}
        for key, rel in sorted(entries.items()):
            block[key] = rel
            full = os.path.join(ROOT, rel)
            if not os.path.exists(full):
                missing.append(rel)
                continue
            if rel not in SELF_REGENERATING and os.path.isfile(full):
                block[key + "_sha256"] = hashing.sha256_file(full)
        record[section] = block

    if missing:
        raise SystemExit("the record would name paths that do not exist: %s"
                         % missing)

    text = json.dumps(record, indent=2, sort_keys=True) + "\n"
    with open(path_policy.assert_writable(OUT), "w", encoding="utf-8") as fh:
        fh.write(text)
    print(json.dumps({"record": os.path.relpath(OUT, ROOT),
                      "sha256": hashing.sha256_text(text),
                      "paths_named": sum(
                          len(v) for k, v in SECTIONS.items()),
                      "digests_unbound": sorted(SELF_REGENERATING)},
                     indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    sys.exit(main())
